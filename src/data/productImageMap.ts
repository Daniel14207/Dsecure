/**
 * Normalise intelligemment une référence produit pour résoudre les variations de nommage:
 * - Remplacement des barres obliques (/) par des tirets (-)
 * - Suppression des espaces et caractères de ponctuation superflus
 * - Mise en minuscules
 */
export function normalizeProductRef(ref: string): string {
  if (!ref) return "";
  return ref.toLowerCase().replace(/[^a-z0-9]/g, "");
}

/**
 * Retourne la véritable photographie officielle du produit si elle existe dans le catalogue.
 * Retourne null si le matériel n a pas encore de photographie originale correspondante (affichage neutre).
 */
export function getProductAuthenticImage(reference: string, id?: string): string | null {
  if (id && PRODUCT_IMAGE_BY_ID[id]) {
    return PRODUCT_IMAGE_BY_ID[id];
  }
  if (reference) {
    if (PRODUCT_IMAGE_BY_REFERENCE[reference]) {
      return PRODUCT_IMAGE_BY_REFERENCE[reference];
    }
    const norm = normalizeProductRef(reference);
    if (PRODUCT_IMAGE_BY_NORMALIZED_REF[norm]) {
      return PRODUCT_IMAGE_BY_NORMALIZED_REF[norm];
    }
  }
  return null;
}
