/**
 * D SECURE - Système Officiel de Packs Vidéosurveillance Clés en Main
 * 
 * Nomenclature interne (Bill of Materials - BOM) et calcul automatique rigoureux
 * Distinction stricte entre technologies ANALOGIQUES et IP NUMÉRIQUES PoE.
 * 
 * RÈGLES DE CONCEPTION & DIMENSIONNEMENT :
 * - Aucune caméra analogique avec NVR IP.
 * - Aucune caméra IP avec DVR analogique.
 * - Connecteurs BNC (2 par caméra) et fiches DC (1 par caméra) uniquement pour l'analogique.
 * - Connecteurs RJ45 certifiés (2 par caméra) uniquement pour l'IP PoE.
 * - Câble coaxial 100m pour analogique / Câble UTP Cat6 carton 305m (DS-1LN6U-W/CCA) pour IP.
 * - NVR avec ports PoE intégrés dédiés (-4P, -8P, -16P).
 * - Installation offerte à Antananarivo (0 Ar).
 */

export interface PackComponentBOM {
  ref: string;
  name: string;
  category: string;
  role: string;
  quantity: number;
  unitPriceAr: number;
  totalPriceAr: number;
  isOffered?: boolean;
  note?: string;
}

export interface SurveillancePack {
  id: string;
  family: 'analog' | 'ip';
  subFamily: 'analog-exir' | 'analog-colorvu' | 'analog-hybrid' | 'ip-poe' | 'ip-pro';
  subFamilyLabel: string;
  name: string;
  tagline: string;
  badge: string;
  technology: string;
  camerasCount: number;
  resolution: string;
  nightVision: string;
  cameraModel: string;
  recorderModel: string;
  storage: string;
  cabling: string;
  powerSupply: string;
  image: string;
  highlights: string[];
  bom: PackComponentBOM[];
  totalPriceAr: number;
  formattedPrice: string;
  installationIncluded: boolean;
}

/**
 * Calcul déterministe et automatique du total d'un pack à partir de sa nomenclature (BOM)
 */
export function calculateBOMTotal(bom: PackComponentBOM[]): number {
  return bom.reduce((sum, item) => {
    if (item.isOffered) return sum;
    return sum + item.unitPriceAr * item.quantity;
  }, 0);
}

export function formatArPrice(amount: number): string {
  return new Intl.NumberFormat('fr-FR').format(amount) + ' Ar';
}

